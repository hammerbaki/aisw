#!/bin/bash
# 수집·요약·통지 파이프라인 (week09 실습용 골격)
#
# 구성: 로그 파일(수집) → claude -p(요약) → 요약.md(통지 대용 기록)
# 사용법: bash pipeline.sh
# 전제: Claude Code 로그인 환경 (학과 키, Haiku)

LOG="서버로그.txt"

cat "$LOG" | claude -p "이 서버 로그의 오류를 원인별로 묶고 심각한 순서로 3줄 이내로 요약하라. 각 줄에 발생 시각 범위를 붙여라. 오류가 없으면 '이상 없음'만 출력하라." > 요약.md

# TODO(실습): 위 명령의 종료 코드를 검사하는 분기를 추가하라.
# 종료 코드($?)가 0이 아니면 "요약 실패: 수동 확인 필요"를 요약.md에 기록하고
# 이 스크립트도 종료 코드 1로 끝나야 한다(뒤에 이어질 자동화가 실패를 알 수 있도록).

echo "완료: 요약.md"
